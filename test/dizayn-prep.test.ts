test('Spanish blog routes generate all surfaces and remain idempotent', { timeout: 700_000 }, async (t) => {
  const source = '/home/darrkito/dizaynseo-esblog';
  if (!existsSync(source)) { t.skip('Spanish blog checkout is not on this machine'); return; }
  const { mkdtempSync, readFileSync, rmSync, mkdirSync, openSync, closeSync } = await import('node:fs');
  const scratchRoot = '/tmp/claude-1000';
  mkdirSync(scratchRoot, { recursive: true });
  const root = mkdtempSync(join(scratchRoot, 'h2-test-')), site = join(root, 'site');
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (cwd: string, ...args: string[]) => {
    const output = join(root, 'git-output'), fd = openSync(output, 'w');
    try { execFileSync('git', args, { cwd, stdio: ['ignore', fd, 'inherit'] }); } finally { closeSync(fd); }
    return readFileSync(output, 'utf8');
  };
  execFileSync('git', ['clone', '-q', source, site], { cwd: root, stdio: 'inherit' });
  const routes = ['/es/blog', '/es/blog/senales-de-que-tu-sitio-web-te-hace-perder-clientes', '/es/blog/como-conseguir-mas-resenas-en-google'];
  const result = JSON.parse(py(join(DIR, 'prep.py'), site));
  assert.deepEqual(result.added.sort(), [...routes].sort());
  for (const route of ['/blog', '/blog/signs-your-website-is-losing-customers', '/blog/how-to-get-more-google-reviews']) assert.ok(result.changed.includes(route));
  const read = (path: string) => readFileSync(join(site, path), 'utf8');
  const sitemap = read('sitemap.xml'), llms = read('llms.txt'), full = read('llms-full.txt');
  const index = JSON.parse(read('api/_index.js').split('module.exports = ')[1].trim().replace(/;$/, ''));
  const vercel = JSON.parse(read('vercel.json'));
  for (const route of routes) {
    assert.ok(read(`${route.slice(1)}.html`).includes('<!-- AEO:agent-discovery -->'));
    assert.match(read(`md${route}.md`), /^language: "es-US"$/m);
    const url = `https://www.dizaynseo.com${route}`;
    assert.equal(sitemap.split(`<loc>${url}</loc>`).length - 1, 1);
    assert.equal(llms.split(`](${url})`).length - 1, 1);
    assert.equal(full.split(`Source: ${url}\n`).length - 1, 1);
    assert.equal(index.find((x: any) => x.route === route)?.language, 'es-US');
    assert.equal(vercel.rewrites.filter((x: any) => x.source === route).length, 2);
    assert.equal(vercel.headers.filter((x: any) => x.source === route).length, 1);
  }
  git(site, 'config', 'user.email', 'test@example.com'); git(site, 'config', 'user.name', 'Test');
  git(site, 'add', '-A'); git(site, 'commit', '-qm', 'Generate Spanish blog');
  assert.equal(py(join(DIR, 'prep.py'), site).trim(), '{"added": [], "changed": []}');
  assert.equal(git(site, 'status', '--porcelain').trim(), '');
});

