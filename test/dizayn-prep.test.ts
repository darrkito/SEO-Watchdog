// Dizayn SEO stand-in for the partner's missing generator: replayed against the committed output (needs the site checkout).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const REPO = '/home/darrkito/dizaynseo', DIR = join(import.meta.dirname, '../src/agents/dizayn');
const skip = !existsSync(join(REPO, '_src/build.py')) && 'the dizaynseo checkout is not on this machine';
const py = (...a: string[]) => execFileSync('python3', a, { encoding: 'utf8', timeout: 600_000, stdio: ['ignore', 'pipe', 'pipe'] });

test('replay: a committed post regenerated by prep.py is byte-identical (page, blog index, twin, sitemap, llms.txt, vercel.json, agent-tools.js)', { skip, timeout: 700_000 }, () => {
  assert.match(py(join(DIR, 'selftest.py'), REPO), /REPLAY OK/);
});

test('a new post written into posts_agent.py reaches every generated file; prep is idempotent; a bad post is refused', { skip, timeout: 700_000 }, () => {
  assert.match(py(join(DIR, 'selftest.py'), '--newpost', REPO), /NEWPOST OK/);
});

test('two drafts made from the same base both publish: the second is re-applied and regenerated on the latest main', { skip, timeout: 900_000 }, async () => {
  const { mkdtempSync, writeFileSync, readFileSync } = await import('node:fs');
  const { tmpdir } = await import('node:os');
  const { prepareWorktree, pushAndVerify } = await import('../src/agents/agents.ts');
  const { dizaynPostEdit } = await import('../src/agents/hooks.ts');
  const root = mkdtempSync(join(tmpdir(), 'wd-regen-')), g = (cwd: string, ...a: string[]) => execFileSync('git', a, { cwd, encoding: 'utf8' });
  g(root, 'clone', '-q', '--bare', REPO, 'remote.git'); g(root, 'clone', '-q', 'remote.git', 'owner');
  const owner = join(root, 'owner'); g(owner, 'config', 'user.email', 't@t'); g(owner, 'config', 'user.name', 't');
  const cfg: any = { repo: owner, worktree: join(root, 'wt'), remote: 'origin', typecheck: ['true'], regenerateFrom: ['_src'], postEdit: dizaynPostEdit };
  const A = 'get-business-recommended-by-chatgpt', B = 'how-much-does-seo-cost-small-business';
  const draft = (branch: string, slug: string, tag: string) => {
    const wt = prepareWorktree(cfg, branch); g(wt, 'config', 'user.email', 't@t'); g(wt, 'config', 'user.name', 't');
    for (const f of ['_src/posts.py', '_src/posts_funnel.py']) {
      const s = readFileSync(join(wt, f), 'utf8'), i = s.indexOf(`"slug": "${slug}"`);
      if (i < 0) continue;
      const j = s.indexOf('"desc": "', i) + 9, k = s.indexOf('",', j);
      writeFileSync(join(wt, f), s.slice(0, k) + ` ${tag}` + s.slice(k));
    }
    dizaynPostEdit(wt, { slug, improve: true, merge: slug });
    g(wt, 'add', '-A'); g(wt, 'commit', '-qm', `Improve ${slug}`);
  };
  draft('agent/a', A, 'TAGA'); draft('agent/b', B, 'TAGB'); // both from the same base
  const wt = cfg.worktree;
  g(wt, 'checkout', '-q', 'agent/a'); pushAndVerify(cfg, [], { slug: A, improve: true, merge: A });
  g(wt, 'checkout', '-q', 'agent/b');
  assert.throws(() => { g(wt, 'rebase', 'origin/main'); try { g(wt, 'rebase', '--abort'); } catch { /* */ } }, 'git alone cannot merge the two drafts');
  g(wt, 'fetch', 'origin', 'main'); pushAndVerify(cfg, [], { slug: B, improve: true, merge: B });
  const main = (f: string) => g(root, '--git-dir=remote.git', 'show', `main:${f}`);
  const idx = main('md/blog.md');
  assert.ok(idx.includes('TAGA') && idx.includes('TAGB'), 'the blog index lists both changes');
  assert.ok(main('blog.html').includes('TAGA') && main('blog.html').includes('TAGB'));
  g(root, 'clone', '-q', 'remote.git', 'check');
  assert.equal(execFileSync('python3', [join(DIR, 'prep.py'), join(root, 'check')], { encoding: 'utf8' }).trim(), '{"added": [], "changed": []}');
  assert.equal(g(join(root, 'check'), 'status', '--porcelain').trim(), '', 'regenerating the published site changes nothing: it is consistent');
});
